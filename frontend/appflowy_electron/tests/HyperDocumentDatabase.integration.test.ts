import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { create, fromBinary, toBinary, type DescMessage, type MessageInitShape } from '@bufbuild/protobuf';
import { afterAll, describe, expect, it, vi } from 'vitest';
import { FlowyErrorSchema } from '@shared/protobuf/flowy-error/errors_pb';
import { ApplyActionPayloadPBSchema, CreateDocumentPayloadPBSchema, DocumentDataPBSchema, OpenDocumentPayloadPBSchema } from '@shared/protobuf/flowy-document/entities_pb';
import { RepeatedRowIdPBSchema, UpdateRowMetaChangesetPBSchema } from '@shared/protobuf/flowy-database2/row_entities_pb';
import { CreateViewPayloadPBSchema, RepeatedViewIdPBSchema, ViewIdPBSchema, ViewLayoutPB, ViewPBSchema } from '@shared/protobuf/flowy-folder/view_pb';
import { WorkspacePBSchema } from '@shared/protobuf/flowy-folder/workspace_pb';
import { SignUpPayloadPBSchema } from '@shared/protobuf/flowy-user/auth_pb';
import { UserProfilePBSchema } from '@shared/protobuf/flowy-user/user_profile_pb';
import { AuthTypePB } from '@shared/protobuf/flowy-user/workspace_pb';
import { CoreProcess } from '../src/main/core/process';
import { Status } from '../src/main/core/protocol';
import { coreBinaryPath } from '../src/main/core/binary';
import { HyperDocumentDatabaseService, type HyperDocumentDatabaseIdentity } from '../src/renderer/features/document-database/HyperDocumentDatabaseService';
import { hyperCaptureDocumentDatabaseAnchor, hyperInsertDocumentDatabase, hyperIsDocumentDatabase, hyperReadDocumentDatabase, type HyperDocumentDatabaseReference } from '../src/renderer/features/document-database/HyperDocumentDatabaseModel';
import { hyperBlockText, hyperChildren, hyperDeleteBlock, hyperEditText, hyperInsertBlock, hyperPlainText, type HyperDocumentChange } from '../src/renderer/features/document/HyperDocumentModel';
import { HyperDatabaseRepository } from '../src/renderer/features/database/HyperDatabaseRepository';
import { hyperDecodeCell } from '../src/renderer/features/database/HyperDatabaseCells';
import { rowDocumentIdForRow } from '../src/renderer/features/templates/converter';

const binary = coreBinaryPath(path.resolve(__dirname, '..'), false);
(fs.existsSync(binary) ? describe : describe.skip)('Hyper inline databases (real core)', () => {
  const support = fs.mkdtempSync(path.join(os.tmpdir(), 'hyper-inline-database-'));
  let core = new CoreProcess(binary), documentId = '';
  let identity: HyperDocumentDatabaseIdentity;
  const service = new HyperDocumentDatabaseService(), repository = new HyperDatabaseRepository();
  const initialize = async () => {
    await core.start(() => {});
    expect(await core.init({ root: support, app_version: '0.11.4', custom_app_path: support, origin_app_path: support, device_id: 'hyper-inline-db-test', platform: process.platform, authenticator_type: 0, appflowy_cloud_config: { base_url: '', ws_base_url: '', gotrue_url: '' }, envs: {} })).toBe(0);
    vi.stubGlobal('window', { appflowy: { core: { request: (event: string, payload: Uint8Array) => core.request(event, payload) } } });
  };
  async function request(event: string, input?: [DescMessage, object]) {
    const bytes = input ? toBinary(input[0], create(input[0], input[1] as MessageInitShape<DescMessage>)) : new Uint8Array();
    let timer: ReturnType<typeof setTimeout> | undefined;
    const reply = await Promise.race([core.request(event, bytes), new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new Error(`Core request timed out: ${event}`)), 15_000); })]).finally(() => clearTimeout(timer));
    if (reply.status !== Status.Ok) throw new Error(`${event}: ${fromBinary(FlowyErrorSchema, reply.payload).msg}`);
    return reply.payload;
  }
  const call = async <O extends DescMessage>(event: string, output: O, input?: [DescMessage, object]) => fromBinary(output, await request(event, input));
  const read = () => call('GetDocumentData', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId }]);
  const apply = async (change: HyperDocumentChange) => { await request('ApplyAction', [ApplyActionPayloadPBSchema, { documentId, actions: change.actions }]); return read(); };
  const options = (layout: ViewLayoutPB, name = 'Inline database') => ({ documentId, identity, layout, name, writable: () => true });
  afterAll(async () => { await core.stop(); fs.rmSync(support, { recursive: true, force: true }); vi.unstubAllGlobals(); });

  it('persists all inline layouts and shared row edits without converting page text', async () => {
    await initialize();
    await call('SignUp', UserProfilePBSchema, [SignUpPayloadPBSchema, { email: 'anon@appflowy.io', name: 'Me', password: 'Guest!@123456', authType: AuthTypePB.Local, deviceId: 'hyper-inline-db-test' }]);
    const workspace = await call('ReadCurrentWorkspace', WorkspacePBSchema);
    const view = await call('CreateView', ViewPBSchema, [CreateViewPayloadPBSchema, { parentViewId: workspace.id, name: 'Inline database document', layout: ViewLayoutPB.Document, setAsCurrent: false }]);
    documentId = view.id; identity = (await service.candidates()).identity;
    let document = await call('OpenDocument', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId }]);
    const paragraph = hyperInsertBlock(document, document.pageId, hyperChildren(document, document.blocks[document.pageId]).at(-1) ?? '', 'paragraph');
    const written = hyperEditText(paragraph.document, paragraph.focus!.id, [{ insert: 'Before 🌍 database', attributes: { italic: true } }]);
    document = await apply({ ...written, actions: [...paragraph.actions, ...written.actions] });
    const savedParagraph = hyperBlockText(document, document.blocks[paragraph.focus!.id]);
    const references: HyperDocumentDatabaseReference[] = [];
    for (const layout of [ViewLayoutPB.Grid, ViewLayoutPB.Board, ViewLayoutPB.Calendar]) {
      const prepared = await service.create(options(layout)); references.push(prepared.reference);
      document = await apply(hyperInsertDocumentDatabase(document, hyperCaptureDocumentDatabaseAnchor(document), prepared.reference));
      expect((await service.resolve(prepared.reference)).id).toBe(prepared.view.id);
      expect((await repository.load(prepared.view.id)).database.layoutType).toBe(layout === ViewLayoutPB.Grid ? 0 : layout === ViewLayoutPB.Board ? 1 : 2);
    }
    const source = references[0], sourceSnapshot = await repository.load(source.viewId);
    const title = sourceSnapshot.fields.find(field => field.isPrimary)!;
    const row = await repository.createRow(source.viewId);
    await repository.updateText(source.viewId, row.id, title.id, 'Shared row 🌍');
    const linked = await service.link(source.viewId, options(ViewLayoutPB.Grid, 'Linked database'));
    references.push(linked.reference);
    expect(linked.reference.parentId).toBe(source.viewId);
    document = await apply(hyperInsertDocumentDatabase(document, hyperCaptureDocumentDatabaseAnchor(document), linked.reference));
    expect((await repository.load(linked.view.id)).database.rows.some(item => item.id === row.id)).toBe(true);
    await repository.updateText(linked.view.id, row.id, title.id, 'Edited through linked view');
    expect(hyperDecodeCell(title, await repository.cell(source.viewId, row.id, title.id)).text).toBe('Edited through linked view');
    expect(hyperBlockText(document, document.blocks[paragraph.focus!.id])).toEqual(savedParagraph);
    await core.stop(); core = new CoreProcess(binary); await initialize();
    document = await call('OpenDocument', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId }]);
    const reopened = hyperChildren(document, document.blocks[document.pageId]).map(id => document.blocks[id]).filter(block => hyperIsDocumentDatabase(block.ty));
    expect(reopened.map(block => hyperReadDocumentDatabase(document, block))).toEqual(references);
    expect(hyperPlainText(hyperBlockText(document, document.blocks[paragraph.focus!.id]))).toBe('Before 🌍 database');
    expect((await repository.load(linked.view.id)).database.rows.some(item => item.id === row.id)).toBe(true);
    expect(hyperDecodeCell(title, await repository.cell(linked.view.id, row.id, title.id)).text).toBe('Edited through linked view');
    // Removing a reference removes only the block, preserving the database and its shared rows.
    document = await apply(hyperDeleteBlock(document, reopened.at(-1)!.id));
    expect((await service.resolve(linked.reference)).id).toBe(linked.view.id);
    expect((await repository.load(source.viewId)).database.rows.some(item => item.id === row.id)).toBe(true);
    await request('DeleteView', [RepeatedViewIdPBSchema, { items: [linked.view.id] }]);
    await expect(service.resolve(linked.reference)).rejects.toThrow();
    expect((await repository.load(source.viewId)).database.rows.some(item => item.id === row.id)).toBe(true);
  });
  it('rejects local writes when the parent page is locked or the caller loses editability', async () => {
    const before = await service.candidates();
    await request('LockView', [ViewIdPBSchema, { value: documentId }]);
    await expect(service.create(options(ViewLayoutPB.Grid))).rejects.toThrow('locked');
    await request('UnlockView', [ViewIdPBSchema, { value: documentId }]);
    await expect(service.create({ ...options(ViewLayoutPB.Grid), writable: () => false })).rejects.toThrow('read-only');
    expect((await service.candidates()).views.map(view => view.id).sort()).toEqual(before.views.map(view => view.id).sort());
  });
  it('inserts into row bodies without a folder row-document and rejects removed or locked owners', async () => {
    const owner = await call('CreateView', ViewPBSchema, [CreateViewPayloadPBSchema, { parentViewId: identity.workspaceId, name: 'Owning database', layout: ViewLayoutPB.Grid, setAsCurrent: false }]);
    await repository.load(owner.id);
    const row = await repository.createRow(owner.id);
    const rowDocumentId = row.oneOfDocumentId.case === 'documentId' && row.oneOfDocumentId.value ? row.oneOfDocumentId.value : rowDocumentIdForRow(row.id);
    await request('CreateDocument', [CreateDocumentPayloadPBSchema, { documentId: rowDocumentId }]);
    await request('UpdateRowMeta', [UpdateRowMetaChangesetPBSchema, { viewId: owner.id, id: row.id, oneOfIsDocumentEmpty: { case: 'isDocumentEmpty', value: false } }]);
    await expect(call('GetView', ViewPBSchema, [ViewIdPBSchema, { value: rowDocumentId }])).rejects.toThrow('GetView');
    let document = await call('OpenDocument', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId: rowDocumentId }]);
    const paragraph = hyperInsertBlock(document, document.pageId, hyperChildren(document, document.blocks[document.pageId]).at(-1) ?? '', 'paragraph');
    const text = hyperEditText(paragraph.document, paragraph.focus!.id, [{ insert: 'Existing row body 🌍', attributes: { bold: true } }]);
    await request('ApplyAction', [ApplyActionPayloadPBSchema, { documentId: rowDocumentId, actions: [...paragraph.actions, ...text.actions] }]);
    document = await call('GetDocumentData', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId: rowDocumentId }]);
    const rowOptions = { ...options(ViewLayoutPB.Board, 'Database inside row'), documentId: rowDocumentId, rowScope: { viewId: owner.id, rowId: row.id } };
    const nested = await service.create(rowOptions);
    expect(nested.reference.parentId).toBe(owner.id);
    const inserted = hyperInsertDocumentDatabase(document, hyperCaptureDocumentDatabaseAnchor(document, paragraph.focus!.id), nested.reference);
    await request('ApplyAction', [ApplyActionPayloadPBSchema, { documentId: rowDocumentId, actions: inserted.actions }]);
    const linked = await service.link(nested.view.id, { ...rowOptions, name: 'Linked database inside row' });
    expect(linked.reference.parentId).toBe(nested.view.id);
    expect((await service.resolve(nested.reference)).id).toBe(nested.view.id);
    const child = await repository.createRow(nested.view.id);
    expect((await repository.load(linked.view.id)).database.rows.some(item => item.id === child.id)).toBe(true);
    const before = (await service.candidates()).views.map(view => view.id).sort();
    await request('LockView', [ViewIdPBSchema, { value: owner.id }]);
    await expect(service.create(rowOptions)).rejects.toThrow('locked');
    await request('UnlockView', [ViewIdPBSchema, { value: owner.id }]);
    await expect(service.create({ ...rowOptions, writable: () => false })).rejects.toThrow('read-only');
    expect((await service.candidates()).views.map(view => view.id).sort()).toEqual(before);
    await core.stop(); core = new CoreProcess(binary); await initialize();
    await repository.load(owner.id);
    document = await call('OpenDocument', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId: rowDocumentId }]);
    const blocks = hyperChildren(document, document.blocks[document.pageId]).map(id => document.blocks[id]);
    expect(blocks.filter(block => hyperIsDocumentDatabase(block.ty)).map(block => hyperReadDocumentDatabase(document, block))).toEqual([nested.reference]);
    expect(hyperBlockText(document, document.blocks[paragraph.focus!.id])).toEqual([{ insert: 'Existing row body 🌍', attributes: { bold: true } }]);
    await expect(call('GetView', ViewPBSchema, [ViewIdPBSchema, { value: rowDocumentId }])).rejects.toThrow('GetView');
    await request('DeleteRows', [RepeatedRowIdPBSchema, { viewId: owner.id, rowIds: [row.id] }]);
    await expect(service.create(rowOptions)).rejects.toThrow();
    await expect(service.link(nested.view.id, rowOptions)).rejects.toThrow();
    expect((await service.resolve(nested.reference)).id).toBe(nested.view.id);
  });
});
