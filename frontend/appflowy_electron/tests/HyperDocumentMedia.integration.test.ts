import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { create, fromBinary, toBinary, type DescMessage, type MessageInitShape } from '@bufbuild/protobuf';
import { afterAll, describe, expect, it, vi } from 'vitest';
import { FlowyErrorSchema } from '@shared/protobuf/flowy-error/errors_pb';
import { ApplyActionPayloadPBSchema, DocumentDataPBSchema, OpenDocumentPayloadPBSchema } from '@shared/protobuf/flowy-document/entities_pb';
import { CreateViewPayloadPBSchema, ViewIdPBSchema, ViewLayoutPB, ViewPBSchema } from '@shared/protobuf/flowy-folder/view_pb';
import { WorkspacePBSchema } from '@shared/protobuf/flowy-folder/workspace_pb';
import { SignUpPayloadPBSchema } from '@shared/protobuf/flowy-user/auth_pb';
import { UserProfilePBSchema } from '@shared/protobuf/flowy-user/user_profile_pb';
import { AuthTypePB } from '@shared/protobuf/flowy-user/workspace_pb';
import { DocumentEventCreateDocument } from '../src/renderer/backend/events/flowy-document';
import { DatabaseEventDeleteRows, DatabaseEventUpdateRowMeta } from '../src/renderer/backend/events/flowy-database2';
import { unwrap } from '../src/renderer/backend/dispatch';
import { CoreProcess } from '../src/main/core/process';
import { Status } from '../src/main/core/protocol';
import { coreBinaryPath } from '../src/main/core/binary';
import { HyperAssets } from '../src/main/HyperAssets';
import { HyperDocumentMediaService } from '../src/renderer/features/document-media/HyperDocumentMediaService';
import { hyperCaptureDocumentMediaAnchor, hyperInsertDocumentMedia, hyperReadDocumentMedia } from '../src/renderer/features/document-media/HyperDocumentMediaModel';
import { hyperBlockText, hyperChildren, hyperDeleteBlock, hyperEditText, hyperInsertBlock, type HyperDocumentChange } from '../src/renderer/features/document/HyperDocumentModel';
import { HyperDatabaseRepository } from '../src/renderer/features/database/HyperDatabaseRepository';
import { rowDocumentIdForRow } from '../src/renderer/features/templates/converter';

const binary = coreBinaryPath(path.resolve(__dirname, '..'), false);
(fs.existsSync(binary) ? describe : describe.skip)('Hyper document media (real core and managed files)', () => {
  const support = fs.mkdtempSync(path.join(os.tmpdir(), 'hyper-document-media-core-'));
  let core = new CoreProcess(binary), documentId = '';
  const service = new HyperDocumentMediaService();
  const initialize = async () => {
    await core.start(() => {});
    expect(await core.init({ root: support, app_version: '0.11.4', custom_app_path: support, origin_app_path: support, device_id: 'hyper-media-test', platform: process.platform, authenticator_type: 0, appflowy_cloud_config: { base_url: '', ws_base_url: '', gotrue_url: '' }, envs: {} })).toBe(0);
    const assets = new HyperAssets(() => support);
    vi.stubGlobal('window', { appflowy: { core: { request: (event: string, payload: Uint8Array) => core.request(event, payload) }, assets: { importFile: (source: string, kind: 'image' | 'file') => assets.importFile(source, kind), previewUrl: (source: string) => assets.previewUrl(source) } } });
  };
  async function request(event: string, input?: [DescMessage, object]) {
    const bytes = input ? toBinary(input[0], create(input[0], input[1] as MessageInitShape<DescMessage>)) : new Uint8Array();
    let timer: ReturnType<typeof setTimeout> | undefined;
    const reply = await Promise.race([core.request(event, bytes), new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new Error(`Core request timed out: ${event}`)), 15_000); })]).finally(() => clearTimeout(timer));
    if (reply.status !== Status.Ok) throw new Error(`${event}: ${fromBinary(FlowyErrorSchema, reply.payload).msg}`);
    return reply.payload;
  }
  const call = async <O extends DescMessage>(event: string, output: O, input?: [DescMessage, object]) => fromBinary(output, await request(event, input));
  const read = () => call('GetDocumentData', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId }]);
  const apply = async (change: HyperDocumentChange) => { await request('ApplyAction', [ApplyActionPayloadPBSchema, { documentId, actions: change.actions }]); return read(); };
  afterAll(async () => { await core.stop(); fs.rmSync(support, { recursive: true, force: true }); vi.unstubAllGlobals(); });

  it('persists upstream image and file blocks across restart and preserves shared managed assets after reference removal', async () => {
    await initialize();
    await call('SignUp', UserProfilePBSchema, [SignUpPayloadPBSchema, { email: 'anon@appflowy.io', name: 'Me', password: 'Guest!@123456', authType: AuthTypePB.Local, deviceId: 'hyper-media-test' }]);
    const workspace = await call('ReadCurrentWorkspace', WorkspacePBSchema);
    documentId = (await call('CreateView', ViewPBSchema, [CreateViewPayloadPBSchema, { parentViewId: workspace.id, name: 'Media document', layout: ViewLayoutPB.Document, setAsCurrent: false }])).id;
    let document = await call('OpenDocument', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId }]);
    const paragraph = hyperInsertBlock(document, document.pageId, hyperChildren(document, document.blocks[document.pageId]).at(-1) ?? '', 'paragraph');
    const written = hyperEditText(paragraph.document, paragraph.focus!.id, [{ insert: 'Before 🌍 media', attributes: { bold: true } }]);
    document = await apply({ ...written, actions: [...paragraph.actions, ...written.actions] });
    const savedText = hyperBlockText(document, document.blocks[paragraph.focus!.id]);
    const imageSource = path.join(support, 'original.png'), fileSource = path.join(support, 'notes.txt');
    fs.writeFileSync(imageSource, Buffer.from([0, 1, 128, 255])); fs.writeFileSync(fileSource, 'Attachment 🌍');
    const identity = await service.start(documentId, () => true), options = { documentId, identity, writable: () => true };
    const image = await service.prepareLocal(imageSource, 'image', { name: 'Image 🌍', caption: 'Caption', alt: 'Accessible image' }, options);
    const file = await service.prepareLocal(fileSource, 'file', { name: 'Notes', caption: '', alt: '' }, options);
    const network = await service.prepareNetwork('https://example.org/report.pdf', 'file', { name: 'Report', caption: '', alt: '' }, options);
    for (const prepared of [image, file, network]) document = await apply(hyperInsertDocumentMedia(document, hyperCaptureDocumentMediaAnchor(document), prepared.media));
    const shared = { ...image.media, id: crypto.randomUUID(), name: 'Shared image' };
    document = await apply(hyperInsertDocumentMedia(document, hyperCaptureDocumentMediaAnchor(document), shared));
    fs.unlinkSync(imageSource); fs.unlinkSync(fileSource);
    expect(hyperBlockText(document, document.blocks[paragraph.focus!.id])).toEqual(savedText);
    await core.stop(); core = new CoreProcess(binary); await initialize();
    document = await call('OpenDocument', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId }]);
    for (const prepared of [image, file, network]) expect(hyperReadDocumentMedia(document, document.blocks[prepared.media.id])).toMatchObject({ kind: prepared.media.kind, source: prepared.media.source, url: prepared.media.url, name: prepared.media.name });
    expect(hyperReadDocumentMedia(document, document.blocks[image.media.id])).toMatchObject({ caption: 'Caption', alt: 'Accessible image' });
    expect(fs.readFileSync(image.media.url)).toEqual(Buffer.from([0, 1, 128, 255])); expect(fs.readFileSync(file.media.url, 'utf8')).toBe('Attachment 🌍');
    document = await apply(hyperDeleteBlock(document, image.media.id));
    expect(hyperReadDocumentMedia(document, document.blocks[shared.id]).url).toBe(image.media.url);
    expect(fs.existsSync(image.media.url)).toBe(true);
    const before = fs.readdirSync(path.join(support, 'images'));
    await request('LockView', [ViewIdPBSchema, { value: documentId }]);
    await expect(service.prepareLocal(file.media.url, 'image', { name: '', caption: '', alt: '' }, options)).rejects.toThrow('locked');
    expect(fs.readdirSync(path.join(support, 'images'))).toEqual(before);
  });
  it('inserts into row document bodies and checks the owning database and exact row after restart', async () => {
    const workspace = await call('ReadCurrentWorkspace', WorkspacePBSchema);
    const database = await call('CreateView', ViewPBSchema, [CreateViewPayloadPBSchema, { parentViewId: workspace.id, name: 'Media row database', layout: ViewLayoutPB.Grid, setAsCurrent: false }]);
    const repository = new HyperDatabaseRepository(); await repository.load(database.id);
    const row = await repository.createRow(database.id);
    documentId = row.oneOfDocumentId.case === 'documentId' && row.oneOfDocumentId.value ? row.oneOfDocumentId.value : rowDocumentIdForRow(row.id);
    unwrap(await DocumentEventCreateDocument({ documentId }));
    unwrap(await DatabaseEventUpdateRowMeta({ viewId: database.id, id: row.id, oneOfIsDocumentEmpty: { case: 'isDocumentEmpty', value: false } }));
    let document = await call('OpenDocument', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId }]);
    const rowScope = { viewId: database.id, rowId: row.id };
    const identity = await service.start(documentId, () => true, undefined, rowScope);
    const source = path.join(support, 'row-file.txt'); fs.writeFileSync(source, 'Row attachment 🌍');
    const prepared = await service.prepareLocal(source, 'file', { name: 'Row attachment', caption: '', alt: '' }, { documentId, identity, writable: () => true, rowScope });
    document = await apply(hyperInsertDocumentMedia(document, hyperCaptureDocumentMediaAnchor(document), prepared.media));
    fs.unlinkSync(source);
    await core.stop(); core = new CoreProcess(binary); await initialize();
    await repository.load(database.id);
    document = await call('OpenDocument', DocumentDataPBSchema, [OpenDocumentPayloadPBSchema, { documentId }]);
    expect(hyperReadDocumentMedia(document, document.blocks[prepared.media.id]).url).toBe(prepared.media.url);
    expect(fs.readFileSync(prepared.media.url, 'utf8')).toBe('Row attachment 🌍');
    expect(await service.start(documentId, () => true, undefined, rowScope)).toEqual(identity);
    await request('LockView', [ViewIdPBSchema, { value: database.id }]);
    await expect(service.start(documentId, () => true, undefined, rowScope)).rejects.toThrow('locked');
    await request('UnlockView', [ViewIdPBSchema, { value: database.id }]);
    unwrap(await DatabaseEventDeleteRows({ viewId: database.id, rowIds: [row.id] }));
    await expect(service.start(documentId, () => true, undefined, rowScope)).rejects.toThrow();
    expect(fs.existsSync(prepared.media.url)).toBe(true);
  });
});
