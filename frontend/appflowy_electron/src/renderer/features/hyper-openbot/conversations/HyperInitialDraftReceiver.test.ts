import { beforeEach, expect, it, vi } from 'vitest';
import { HyperConversationDraftCache, type HyperDraftAttachment } from '../HyperConversationDraft';
import { HyperInitialDraftTransfer, hyperReceiveInitialDraft, type HyperInitialDraft } from './HyperInitialDraftTransfer';
import { hyperOpenBotFetch } from '../transport';
import { hyperDeferred } from './HyperVoiceDeferred';
vi.mock('../transport', () => ({ hyperOpenBotFetch: vi.fn(), hyperOpenBotRequest: vi.fn(), HYPER_OPENBOT_ORIGIN: 'https://hyper-openbot.invalid' }));
beforeEach(() => vi.resetAllMocks());
const response = (id: string) => new Response(JSON.stringify({ id, name: id + '.txt', mimeType: 'text/plain' }));
it('keeps upload bookkeeping with the retained transaction when the receiving page remounts', async () => {
  const transfer = new HyperInitialDraftTransfer<string>();
  const lease = new HyperConversationDraftCache(() => 'group').acquire('channel');
  const initial = { text: 'task', files: [new File(['one'], 'one.txt')], commandIds: [], submit: true };
  let uploads = 0;
  vi.mocked(hyperOpenBotFetch).mockImplementation(async () => response(`upload-${++uploads}`));
  const send = vi.fn().mockRejectedValueOnce(new Error('send failed')).mockResolvedValueOnce(undefined);
  const create = vi.fn().mockResolvedValue('channel');
  const deps = { create, navigate: vi.fn(), receive: (channel: string, draft: HyperInitialDraft, signal: AbortSignal, uploaded?: Map<File, HyperDraftAttachment>) => hyperReceiveInitialDraft(channel, draft, signal, { ...lease, uploaded: uploaded ?? new Map(), send }) };
  await expect(transfer.start(['bot'], initial, deps)).rejects.toThrow('send failed');
  await transfer.start(['bot'], initial, deps);
  expect(create).toHaveBeenCalledOnce(); expect(hyperOpenBotFetch).toHaveBeenCalledOnce();
  expect(send.mock.calls[1][0].attachments.map((file: HyperDraftAttachment) => file.id)).toEqual(['upload-1']);
});
it('rejects initial uploads that would exceed the existing conversation attachment limit', async () => {
  const lease = new HyperConversationDraftCache(() => 'group').acquire('channel');
  lease.update(current => ({ ...current, attachments: Array.from({ length: 8 }, (_, index) => ({ id: `saved-${index}`, name: 'saved.txt', mimeType: 'text/plain', status: 'ready' })) }));
  vi.mocked(hyperOpenBotFetch).mockResolvedValueOnce(response('extra'));
  const send = vi.fn();
  await expect(hyperReceiveInitialDraft('channel', { text: 'task', files: [new File(['extra'], 'extra.txt')], commandIds: [], submit: true }, new AbortController().signal, { ...lease, uploaded: new Map(), send })).rejects.toThrow('eight-file limit');
  expect(hyperOpenBotFetch).not.toHaveBeenCalled(); expect(send).not.toHaveBeenCalled();
});
it('awaits every upload and send, passes files unchanged, and clears only after success', async () => {
  const lease = new HyperConversationDraftCache(() => 'group').acquire('channel');
  const files = [new File(['one'], 'one.txt'), new File(['two'], 'two.txt')];
  const first = hyperDeferred<Response>(); const second = hyperDeferred<Response>(); const sent = hyperDeferred<void>();
  vi.mocked(hyperOpenBotFetch).mockReturnValueOnce(first.promise).mockReturnValueOnce(second.promise);
  const send = vi.fn(() => sent.promise);
  const work = hyperReceiveInitialDraft('channel', { text: '/skill task', files, commandIds: ['skill'], submit: true }, new AbortController().signal, { ...lease, uploaded: new Map(), send });
  expect(lease.get().attachments.map(file => file.status)).toEqual(['uploading', 'uploading']);
  const form = vi.mocked(hyperOpenBotFetch).mock.calls[0][1]!.body as FormData;
  expect(form.get('file')).toBe(files[0]); expect(form.get('uploadGroup')).toBe('group');
  first.resolve(response('one')); await vi.waitFor(() => expect(hyperOpenBotFetch).toHaveBeenCalledTimes(2));
  expect(send).not.toHaveBeenCalled(); second.resolve(response('two'));
  await vi.waitFor(() => expect(send).toHaveBeenCalledTimes(1));
  expect(lease.get().text).toBe('/skill task'); expect(lease.get().commandIds).toEqual(['skill']);
  sent.resolve(); await work; expect(lease.get().text).toBe(''); expect(lease.get().attachments).toEqual([]);
});
it('keeps a populated draft without sending and preserves uploads across refused-send retry', async () => {
  const lease = new HyperConversationDraftCache(() => 'group').acquire('channel');
  const uploaded = new Map(); const file = new File(['one'], 'one.txt');
  const initial = { text: '/skill task', files: [file], commandIds: ['skill'], submit: false };
  vi.mocked(hyperOpenBotFetch).mockResolvedValueOnce(response('one'));
  const send = vi.fn().mockRejectedValueOnce(new Error('refused')).mockResolvedValueOnce(undefined);
  const deps = { ...lease, uploaded, send }; const signal = new AbortController().signal;
  await hyperReceiveInitialDraft('channel', initial, signal, deps); expect(send).not.toHaveBeenCalled();
  expect(lease.get().text).toBe(initial.text); expect(lease.get().commandIds).toEqual(['skill']);
  await expect(hyperReceiveInitialDraft('channel', { ...initial, submit: true }, signal, deps)).rejects.toThrow('refused');
  expect(lease.get().attachments).toHaveLength(1); expect(lease.get().text).toBe(initial.text);
  await hyperReceiveInitialDraft('channel', { ...initial, submit: true }, signal, deps);
  expect(hyperOpenBotFetch).toHaveBeenCalledTimes(1);
});
it('rejects upload refusal and cancellation without sending or losing the draft', async () => {
  const lease = new HyperConversationDraftCache(() => 'group').acquire('channel'); const send = vi.fn();
  vi.mocked(hyperOpenBotFetch).mockResolvedValueOnce(new Response('{}', { status: 403 }));
  const initial = { text: 'task', files: [new File(['one'], 'one.txt')], commandIds: [], submit: true };
  await expect(hyperReceiveInitialDraft('channel', initial, new AbortController().signal, { ...lease, uploaded: new Map(), send })).rejects.toThrow();
  expect(send).not.toHaveBeenCalled(); expect(lease.get().text).toBe('task'); expect(lease.get().attachments).toEqual([]);
  const controller = new AbortController(); controller.abort();
  await expect(hyperReceiveInitialDraft('channel', initial, controller.signal, { ...lease, uploaded: new Map(), send })).rejects.toThrow();
  expect(hyperOpenBotFetch).toHaveBeenCalledTimes(1);
});
